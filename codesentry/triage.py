"""
Review Triage - Decide which files deserve an (expensive) AI review

Not every file needs an LLM to look at it. Reviewing a clean, idiomatic file
mostly produces nitpicks, which is the main reason developers reject AI
review comments. The triage gate skips a file when it is confidently fine and
spends the review budget on the riskiest files instead.

Decision order (first match wins):
  1. Must-review overrides - secrets / prompt-injection hits, security
     sensitive paths, or security-regression signals. Never skipped.
  2. Deterministic skips - generated files, near-empty files, oversized
     files, and diffs that only touch whitespace or comments.
  3. Static-clean check - files with any error/security/warning findings or
     high complexity always get reviewed.
  4. LLM triage (mode: hybrid) - a cheap, short "is this LGTM?" call for the
     remaining static-clean files. Skipped only on a confident LGTM.

Modes: `off` (review everything), `static` (skip static-clean files without
asking the LLM), `hybrid` (default; ask the LLM before skipping).
"""

import fnmatch
import math
import os
import re
from dataclasses import dataclass, field
from typing import Any, Callable, Dict, Iterable, List, Optional

from .findings import extract_json
from .guardrails import SanitizedInput, fence_untrusted, UNTRUSTED_PREAMBLE

ACTION_REVIEW = 'review'
ACTION_SKIP = 'skip'

DEFAULT_GENERATED_PATTERNS = [
    '*_pb2.py', '*_pb2_grpc.py', '*.pb.go', '*.generated.*', '*.g.dart',
    '*.min.js', '*.bundle.js', '*_generated.go', 'migrations/*.py',
]
GENERATED_MARKERS = re.compile(
    r'(?i)@generated|do not edit|code generated by|auto-?generated|this file was automatically generated'
)
DEFAULT_SENSITIVE_PATHS = [
    '*auth*', '*login*', '*password*', '*crypto*', '*token*', '*secret*',
    '*payment*', '*billing*', '*permission*', '*acl*', '*session*', '*security*',
]

_COMMENT_PREFIXES = ('#', '//', '/*', '*', '*/', '"""', "'''", '--', '<!--')


@dataclass
class TriageDecision:
    file: str
    action: str
    reason: str
    risk: float = 0.0
    details: Dict[str, Any] = field(default_factory=dict)

    @property
    def skipped(self) -> bool:
        return self.action == ACTION_SKIP


def is_comment_or_blank(line: str) -> bool:
    stripped = line.strip()
    return not stripped or stripped.startswith(_COMMENT_PREFIXES)


def meaningful_line_count(content: str) -> int:
    return sum(1 for line in content.splitlines() if not is_comment_or_blank(line))


class ReviewTriage:
    """Decides, per file, whether the AI review should run"""

    TRIAGE_PROMPT = """You are triaging files for code review. Decide whether this file needs a detailed review.

Answer LGTM only if ALL of the following hold:
- no bugs, logic errors, or unhandled edge cases you can see
- no security, performance, or error-handling problems
- it follows the conventions of its language
- there is no materially simpler or more correct approach

{preamble}

File: {file}
{code}

Respond with ONLY JSON: {{"verdict": "LGTM" | "NEEDS_REVIEW", "confidence": <0.0-1.0>, "reason": "<one sentence>"}}"""

    def __init__(self, config: Dict[str, Any]):
        cfg = (config.get('guardrails', {}) or {}).get('triage', {}) or {}
        self.mode = cfg.get('mode', 'hybrid')
        self.lgtm_confidence = float(cfg.get('lgtm_confidence', 0.8))
        self.min_meaningful_lines = int(cfg.get('min_meaningful_lines', 3))
        self.max_file_lines = int(cfg.get('max_file_lines', 2000))
        self.generated_patterns = cfg.get('generated_patterns', DEFAULT_GENERATED_PATTERNS)
        self.sensitive_paths = cfg.get('sensitive_paths', DEFAULT_SENSITIVE_PATHS)
        self.triage_chars = int(cfg.get('triage_max_chars', 6000))

    # ------------------------------------------------------------------

    def decide(
        self,
        file_path: str,
        content: str,
        file_issues: Iterable[Dict[str, Any]],
        sanitized: Optional[SanitizedInput] = None,
        changed_lines: Optional[List[str]] = None,
        high_complexity: int = 0,
        llm_call: Optional[Callable[[str], str]] = None,
        must_review_reasons: Optional[List[str]] = None,
    ) -> TriageDecision:
        issues = list(file_issues)
        risk = self.risk_score(file_path, content, issues, sanitized, high_complexity)

        def review(reason: str, **details) -> TriageDecision:
            return TriageDecision(file_path, ACTION_REVIEW, reason, risk, details)

        def skip(reason: str, **details) -> TriageDecision:
            return TriageDecision(file_path, ACTION_SKIP, reason, risk, details)

        if self.mode == 'off':
            return review('triage disabled')

        # 1. Must-review overrides
        if sanitized and sanitized.injections:
            return review('possible prompt injection in file')
        if sanitized and sanitized.secrets:
            return review('hardcoded secret detected')
        if must_review_reasons:
            return review('; '.join(must_review_reasons))
        sensitive = self._is_sensitive(file_path)

        # 2. Deterministic skips
        if self._is_generated(file_path, content):
            return skip('generated or vendored file')
        if meaningful_line_count(content) < self.min_meaningful_lines:
            return skip('trivial file (too little code to review)')
        if content.count('\n') + 1 > self.max_file_lines:
            return skip(f'file exceeds {self.max_file_lines} lines; static analysis only')
        if changed_lines is not None and changed_lines and all(is_comment_or_blank(l) for l in changed_lines):
            return skip('change only touches comments or whitespace')

        # 3. Static signals
        blocking = [i for i in issues if i.get('severity') in ('error', 'security', 'warning')]
        if blocking:
            return review(f'{len(blocking)} static analysis issue(s)')
        if high_complexity:
            return review(f'{high_complexity} high-complexity function(s)')
        if sensitive:
            return review('security-sensitive path')

        # 4. Static-clean: skip outright, or ask the LLM first
        if self.mode == 'static' or llm_call is None:
            return skip('passes all static checks')

        return self._llm_triage(file_path, sanitized.text if sanitized else content, llm_call, risk)

    def _llm_triage(self, file_path: str, content: str, llm_call: Callable[[str], str],
                    risk: float) -> TriageDecision:
        prompt = self.TRIAGE_PROMPT.format(
            preamble=UNTRUSTED_PREAMBLE,
            file=file_path,
            code=fence_untrusted(content[:self.triage_chars], os.path.basename(file_path)),
        )
        response = llm_call(prompt)
        data = extract_json(response) if isinstance(response, str) else None
        if not isinstance(data, dict):
            return TriageDecision(file_path, ACTION_REVIEW, 'LLM triage inconclusive', risk)

        verdict = str(data.get('verdict', '')).upper()
        try:
            confidence = float(data.get('confidence', 0))
        except (TypeError, ValueError):
            confidence = 0.0
        reason = str(data.get('reason', '')).strip()[:200]

        if verdict == 'LGTM' and confidence >= self.lgtm_confidence:
            return TriageDecision(file_path, ACTION_SKIP, f'LLM triage: LGTM ({reason})' if reason else 'LLM triage: LGTM',
                                  risk, {'confidence': confidence})
        return TriageDecision(file_path, ACTION_REVIEW, f'LLM triage: {reason or verdict.lower()}',
                              risk, {'confidence': confidence})

    # ------------------------------------------------------------------

    def risk_score(self, file_path: str, content: str, issues: List[Dict[str, Any]],
                   sanitized: Optional[SanitizedInput], high_complexity: int) -> float:
        """Heuristic used to spend a limited review budget on the riskiest files first"""
        weights = {'security': 8, 'error': 5, 'warning': 2, 'info': 0.25}
        score = sum(weights.get(i.get('severity'), 0) for i in issues)
        score += 3 * high_complexity
        if sanitized and sanitized.is_suspicious:
            score += 10
        if self._is_sensitive(file_path):
            score += 5
        score += math.log1p(meaningful_line_count(content))
        return round(score, 2)

    def _is_generated(self, file_path: str, content: str) -> bool:
        normalized = file_path.replace(os.sep, '/')
        name = os.path.basename(normalized)
        for pattern in self.generated_patterns:
            if fnmatch.fnmatch(name, pattern) or fnmatch.fnmatch(normalized, f'*{pattern}'):
                return True
        head = '\n'.join(content.splitlines()[:5])
        return bool(GENERATED_MARKERS.search(head))

    def _is_sensitive(self, file_path: str) -> bool:
        # Only look at the file name and its parent directory, so an absolute
        # checkout path like /home/author/... doesn't make everything "sensitive"
        tail = '/'.join(file_path.replace(os.sep, '/').lower().split('/')[-2:])
        return any(fnmatch.fnmatch(tail, pattern) for pattern in self.sensitive_paths)
